/*
 * add an event to dbShoppingEvent table: return id generated by sql autoincrement
 */

function add_shoppingEvent($personId, $familySize, $date) {
    $con=connect();
    mysqli_query($con,'INSERT INTO dbshoppingevent (personId, familySize, date) VALUES("' .
            $personId . '","' . 
            $familySize . '","' . 
            $date . '");');							
    $id = mysqli_insert_id($con);
    mysqli_close($con);
    
    return $id;
}

/*
 * remove an event from dbEvents table.  If already there, return false
 */

function remove_shoppingEvent($id) {
    $con=connect();
    $query = 'SELECT * FROM dbshoppingevent WHERE id = "' . $id . '"';
    $result = mysqli_query($con,$query);
    if ($result == null || mysqli_num_rows($result) == 0) {
        mysqli_close($con);
        return false;
    }
    $query = 'DELETE FROM dbshoppingevent WHERE id = "' . $id . '"';
    $result = mysqli_query($con,$query);

    mysqli_close($con);
    return true;
}


/*
 * @return an Event from dbEvents table matching a particular id.
 * if not in table, return false
 */

function retrieve_shoppingEvent($id) {
    $con=connect();
    $query = "SELECT * FROM dbshoppingevent WHERE id = '" . $id . "'";
    $result = mysqli_query($con,$query);
    if (mysqli_num_rows($result) !== 1) {
        mysqli_close($con);
        return false;
    }
    $result_row = mysqli_fetch_assoc($result);
    $theEvent = make_an_shoppingEvent($result_row);
    mysqli_close($con);
    return $theEvent;
}

