function update_shoppingEvent_date($id, $new_event_date) {
	$con=connect();
	$query = 'UPDATE dbshoppingevent SET date = "' . $new_event_date . '" WHERE id = "' . $id . '"';
	$result = mysqli_query($con,$query);
	mysqli_close($con);
	return $result;
}

function make_an_shoppingEvent($result_row) {
	/*
	 ($en, $v, $sd, $description, $ev))
	 */
    $theEvent = new ShoppingEvent(
                    $result_row['id'],
                    $result_row['personId'],
                    $result_row['familySize'],
                    $result_row['date']
                );
    return $theEvent;
}

/*
 * return an array of all the Inventory Events
 */

function get_all_shoppingEvents() {
    $con=connect();
    $query = "SELECT * FROM dbshoppingevent";
    $result = mysqli_query($con,$query);
    $theEvents = array();
    while ($result_row = mysqli_fetch_assoc($result)) {
        $theEvent = make_an_shoppingEvent($result_row);
        $theEvents[] = $theEvent;
    }
    mysqli_close($con);
    return $theEvents;
 }

/*
 * return an array of all the Inventory Events with a given date
 * Events are ordered Newest to Oldest
 */

 function get_all_shoppingEvents_by_date($date) {
    $con=connect();
    $query = "SELECT * FROM dbshoppingevent WHERE date = '" . $date . "' ORDER BY id DESC";
    $result = mysqli_query($con,$query);
    $theEvents = array();
    while ($result_row = mysqli_fetch_assoc($result)) {
        $theEvent = make_an_shoppingEvent($result_row);
        $theEvents[] = $theEvent;
    }
    mysqli_close($con);
    return $theEvents;
 }


