/*
 * return an array of all the Inventory Events
 */

function get_all_inventoryEvents() {
    $con=connect();
    $query = "SELECT * FROM dbinventoryevent";
    $result = mysqli_query($con,$query);
    $theEvents = array();
    while ($result_row = mysqli_fetch_assoc($result)) {
        $theEvent = make_an_inventoryEvent($result_row);
        $theEvents[] = $theEvent;
    }
    mysqli_close($con);
    return $theEvents;
 }

/*
 * return an array of all the Inventory Events with a given date
 * Events are ordered Newest to Oldest
 */

 function get_all_inventoryEvents_by_date($date) {
    $con=connect();
    $query = "SELECT * FROM dbinventoryevent WHERE date = '" . $date . "' ORDER BY id DESC";
    $result = mysqli_query($con,$query);
    $theEvents = array();
    while ($result_row = mysqli_fetch_assoc($result)) {
        $theEvent = make_an_inventoryEvent($result_row);
        $theEvents[] = $theEvent;
    }
    mysqli_close($con);
    return $theEvents;
 }

/*
 * return all Inventory Events that pair with given event (Warehouse, Pantry, Pallet)
 * returns array keyed by location: ['Pantry' => event, 'Pallet' => event]
 * uses closest ID logic for multiple entries per date
 */

function get_matching_inventoryEvent($first_event){
    $event_date = $first_event->getDate();
    $first_location = $first_event->getLocation();
    $first_id = $first_event->getId();

    $all_events = get_all_inventoryEvents_by_date($event_date);

    $results = array();
    foreach($all_events as $event){
        $location = $event->getLocation();
        if($location != $first_location){
            if(!isset($results[$location]) ||
               abs($event->getId() - $first_id) < abs($results[$location]->getId() - $first_id)){
                $results[$location] = $event;
            }
        }
    }

    return $results;
}

