/*
 * add an event to dbinventoryevent table: return id generated by sql autoincrement
 */

function add_inventoryEvent($personId, $location, $date) {
    $con=connect();
    mysqli_query($con,'INSERT INTO dbinventoryevent (personId, location, date) VALUES("' .
            $personId . '","' . 
            $location . '","' . 
            $date . '");');							
    $id = mysqli_insert_id($con);
    mysqli_close($con);
    
    return $id;
}

/*
 * remove an event from dbEvents table.  If already there, return false
 */

function remove_inventoryEvent($id) {
    $con = connect();

    /* Check if event exists */
    $query = 'SELECT * FROM dbinventoryevent WHERE id = "' . $id . '"';
    $result = mysqli_query($con, $query);
    if ($result == null || mysqli_num_rows($result) == 0) {
        mysqli_close($con);
        return false;
    }

    /* Step 1: Delete all child itemcounts first (prevents orphaned records) */
    $deleteItems = 'DELETE FROM dbitemcounts WHERE inventoryEventId = "' . $id . '"';
    mysqli_query($con, $deleteItems);

    /* Step 2: Delete the inventory event */
    $query = 'DELETE FROM dbinventoryevent WHERE id = "' . $id . '"';
    $result = mysqli_query($con, $query);

    mysqli_close($con);
    return true;
}

/*
 * @return an Event from dbEvents table matching a particular id.
 * if not in table, return false
 */

function retrieve_inventoryEvent($id) {
    $con=connect();
    $query = "SELECT * FROM dbinventoryevent WHERE id = '" . $id . "'";
    $result = mysqli_query($con,$query);
    if (mysqli_num_rows($result) !== 1) {
        mysqli_close($con);
        return false;
    }
    $result_row = mysqli_fetch_assoc($result);
    // var_dump($result_row);
    $theEvent = make_an_inventoryEvent($result_row);
    mysqli_close($con);
    return $theEvent;
}

