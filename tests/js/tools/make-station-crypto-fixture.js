const subtle = globalThis.crypto.subtle;
const enc = new TextEncoder();
const seq = (from, n) => Uint8Array.from({ length: n }, (_, i) => from + i);
const hex = (b) => [...new Uint8Array(b)].map((x) => x.toString(16).padStart(2, '0')).join('');
const b64url = (b) => Buffer.from(new Uint8Array(b)).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const sha256 = async (d) => hex(await subtle.digest('SHA-256', typeof d === 'string' ? enc.encode(d) : d));
const hmac = async (keyBytes, msg) => {
  const k = await subtle.importKey('raw', keyBytes, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return new Uint8Array(await subtle.sign('HMAC', k, typeof msg === 'string' ? enc.encode(msg) : msg));
};
const hkdf = async (ikm, info) => {
  const k = await subtle.importKey('raw', ikm, 'HKDF', false, ['deriveBits']);
  return new Uint8Array(await subtle.deriveBits({ name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(0), info: enc.encode(info) }, k, 256));
};
const gcm = async (keyBytes, iv, data, aad) => {
  const k = await subtle.importKey('raw', keyBytes, 'AES-GCM', false, ['encrypt']);
  return new Uint8Array(await subtle.encrypt({ name: 'AES-GCM', iv, additionalData: enc.encode(aad), tagLength: 128 }, k, data));
};
const pbkdf2 = async (password, salt, rounds) => {
  const k = await subtle.importKey('raw', enc.encode(password), 'PBKDF2', false, ['deriveBits']);
  return new Uint8Array(await subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations: rounds }, k, 256));
};
const lower = (s) => [...s.replace(/^[ \t\n\r\0\x0B]+|[ \t\n\r\0\x0B]+$/g, '').normalize('NFC')].map((c) => c.toLowerCase()).join('');

