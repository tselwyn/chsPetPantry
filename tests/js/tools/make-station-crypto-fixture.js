/** The §3.9 table and the trim/lower cases: the mismatches (an empty list when the fixture is right). */
export async function checkExpected(fixture) {
  const at = (o, path) => path.split('.').reduce((x, k) => x?.[k], o);
  const bad = [];
  for (const [path, want] of Object.entries(EXPECTED)) if (at(fixture, path) !== want) bad.push(`${path}: ${at(fixture, path)} != ${want}`);
  for (const i of [1, 2, 3]) if (fixture.lookup.cases[i].hash !== fixture.lookup.cases[0].hash) bad.push('lookup case ' + i + ' must equal JDoe');
  if (!(await sha256('pfpms/v1/user|7|' + 'JDoe '.toLowerCase())).startsWith('9bf0ccdf')) bad.push('the untrimmed JDoe value changed');
  return bad;
}

/** ASCII-only file: every code unit above U+007E is written as \uXXXX (JSON.parse and json_decode read it back). */
export function asciiJson(value) {
  return JSON.stringify(value, null, 2).replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0')) + '\n';
}

export const FIXTURE_URL = new URL('../../fixtures/station_crypto.json', import.meta.url);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const fixture = await buildFixture();
  const bad = await checkExpected(fixture);
  if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
  const arg = process.argv.slice(2).find((a) => !a.startsWith('--'));
  const out = arg ? pathToFileURL(arg) : FIXTURE_URL;
  const text = asciiJson(fixture);
  if (process.argv.includes('--check')) process.exit(readFileSync(out, 'utf8') === text ? 0 : 1);
  writeFileSync(out, text);
  console.log('wrote ' + fileURLToPath(out) + ' (' + text.length + ' bytes)');
}
